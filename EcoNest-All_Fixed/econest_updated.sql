-- EcoNest e-commerce database | MySQL 8.0+
-- Execute in MySQL Workbench. Does not delete existing tables.
CREATE DATABASE IF NOT EXISTS ECONEST CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ECONEST;

CREATE TABLE IF NOT EXISTS USERS (
 USER_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 FULL_NAME VARCHAR(120) NOT NULL,
 EMAIL VARCHAR(255) NOT NULL UNIQUE,
 PASSWORD_HASH VARCHAR(255) NOT NULL,
 PHONE VARCHAR(15),
 CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS CATEGORIES (
 CATEGORY_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 CATEGORY_NAME VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS PRODUCTS (
 PRODUCT_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 CATEGORY_ID INT UNSIGNED NOT NULL,
 PRODUCT_NAME VARCHAR(180) NOT NULL,
 PRICE DECIMAL(10,2) NOT NULL,
 ORIGINAL_PRICE DECIMAL(10,2),
 RATING DECIMAL(3,2) DEFAULT 0,
 ECO_SCORE TINYINT UNSIGNED,
 MATERIAL VARCHAR(255),
 IMAGE_URL TEXT,
 IMAGE_ALT VARCHAR(255),
 STOCK_QUANTITY INT UNSIGNED NOT NULL DEFAULT 0,
 IMPACT_DESCRIPTION TEXT,
 IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT FK_PRODUCT_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID),
 CONSTRAINT CK_PRODUCT_PRICE CHECK (PRICE >= 0),
 CONSTRAINT CK_PRODUCT_ORIGINAL CHECK (ORIGINAL_PRICE IS NULL OR ORIGINAL_PRICE >= 0),
 CONSTRAINT CK_PRODUCT_RATING CHECK (RATING BETWEEN 0 AND 5),
 CONSTRAINT CK_PRODUCT_ECO CHECK (ECO_SCORE IS NULL OR ECO_SCORE <= 100)
);

CREATE TABLE IF NOT EXISTS PRODUCT_FEATURES (
 FEATURE_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 PRODUCT_ID INT UNSIGNED NOT NULL,
 FEATURE_TEXT VARCHAR(255) NOT NULL,
 FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS PRODUCT_CERTIFICATIONS (
 PRODUCT_ID INT UNSIGNED NOT NULL,
 CERTIFICATION_NAME VARCHAR(100) NOT NULL,
 PRIMARY KEY (PRODUCT_ID, CERTIFICATION_NAME),
 FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ADDRESSES (
 ADDRESS_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 USER_ID BIGINT UNSIGNED NOT NULL,
 RECIPIENT_NAME VARCHAR(120) NOT NULL,
 PHONE VARCHAR(15) NOT NULL,
 ADDRESS_LINE TEXT NOT NULL,
 CITY VARCHAR(100) NOT NULL,
 PIN_CODE CHAR(6) NOT NULL,
 IS_DEFAULT BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS CART_ITEMS (
 USER_ID BIGINT UNSIGNED NOT NULL,
 PRODUCT_ID INT UNSIGNED NOT NULL,
 QUANTITY INT UNSIGNED NOT NULL DEFAULT 1,
 UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY (USER_ID, PRODUCT_ID),
 FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
 FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
 CONSTRAINT CK_CART_QUANTITY CHECK (QUANTITY > 0)
);

CREATE TABLE IF NOT EXISTS WISHLIST (
 USER_ID BIGINT UNSIGNED NOT NULL,
 PRODUCT_ID INT UNSIGNED NOT NULL,
 ADDED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (USER_ID, PRODUCT_ID),
 FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
 FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID)
);

CREATE TABLE IF NOT EXISTS ORDERS (
 ORDER_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ORDER_NUMBER VARCHAR(40) NOT NULL UNIQUE,
 USER_ID BIGINT UNSIGNED NULL,
 CUSTOMER_NAME VARCHAR(120) NOT NULL,
 CUSTOMER_EMAIL VARCHAR(255) NOT NULL,
 CUSTOMER_PHONE VARCHAR(15) NOT NULL,
 SHIPPING_ADDRESS TEXT NOT NULL,
 SHIPPING_CITY VARCHAR(100) NOT NULL,
 SHIPPING_PIN CHAR(6) NOT NULL,
 STATUS ENUM('Placed','Confirmed','Packed','Shipped','Out for Delivery','Delivered','Cancelled') NOT NULL DEFAULT 'Placed',
 SUBTOTAL DECIMAL(10,2) NOT NULL,
 DISCOUNT DECIMAL(10,2) NOT NULL DEFAULT 0,
 GST_AMOUNT DECIMAL(10,2) NOT NULL DEFAULT 0,
 SHIPPING_FEE DECIMAL(10,2) NOT NULL DEFAULT 0,
 CARBON_OFFSET_FEE DECIMAL(10,2) NOT NULL DEFAULT 0,
 ROUNDUP_DONATION DECIMAL(10,2) NOT NULL DEFAULT 0,
 TOTAL_AMOUNT DECIMAL(10,2) NOT NULL,
 ESTIMATED_DELIVERY VARCHAR(100),
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE SET NULL,
 INDEX IDX_ORDERS_USER_DATE (USER_ID, CREATED_AT)
);

CREATE TABLE IF NOT EXISTS ORDER_ITEMS (
 ORDER_ITEM_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ORDER_ID BIGINT UNSIGNED NOT NULL,
 PRODUCT_ID INT UNSIGNED NOT NULL,
 PRODUCT_NAME VARCHAR(180) NOT NULL,
 QUANTITY INT UNSIGNED NOT NULL,
 UNIT_PRICE DECIMAL(10,2) NOT NULL,
 LINE_TOTAL DECIMAL(10,2) GENERATED ALWAYS AS (QUANTITY * UNIT_PRICE) STORED,
 FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID) ON DELETE CASCADE,
 FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
 CONSTRAINT CK_ORDER_QUANTITY CHECK (QUANTITY > 0)
);

CREATE TABLE IF NOT EXISTS PAYMENTS (
 PAYMENT_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ORDER_ID BIGINT UNSIGNED NOT NULL UNIQUE,
 PAYMENT_METHOD ENUM('UPI','Card','Cash on Delivery') NOT NULL,
 PAYMENT_STATUS ENUM('Pending','Authorized','Paid','Failed','Refunded') NOT NULL DEFAULT 'Pending',
 AMOUNT DECIMAL(10,2) NOT NULL,
 PROVIDER_TRANSACTION_ID VARCHAR(150) UNIQUE,
 PAID_AT DATETIME NULL,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID) ON DELETE CASCADE
);
-- Do not store CVV, full card number, or raw UPI credentials.

CREATE TABLE IF NOT EXISTS ORDER_TRACKING (
 TRACKING_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ORDER_ID BIGINT UNSIGNED NOT NULL,
 STATUS VARCHAR(60) NOT NULL,
 DETAILS VARCHAR(255),
 UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS CONTACT_MESSAGES (
 MESSAGE_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 USER_ID BIGINT UNSIGNED NULL,
 SENDER_NAME VARCHAR(120) NOT NULL,
 SENDER_EMAIL VARCHAR(255) NOT NULL,
 SUBJECT VARCHAR(200) NOT NULL,
 MESSAGE TEXT NOT NULL,
 STATUS ENUM('New','In Progress','Resolved') NOT NULL DEFAULT 'New',
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS RECENTLY_VIEWED (
 USER_ID BIGINT UNSIGNED NOT NULL,
 PRODUCT_ID INT UNSIGNED NOT NULL,
 VIEWED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY (USER_ID, PRODUCT_ID),
 FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
 FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID)
);

